async function seed() {
  const prisma = createPrismaClient(process.env.DATABASE_URL!);
  const now = new Date();
  const profileData = {
    basics: {
      name: "",
      email: "",
      phone: "",
      headline: "",
      city: "Paris",
      country: "France",
      dob: "",
      website: "",
      address: "",
      linkedin: "",
      summary: "",
      showAge: false,
    },
    skills: [],
    experience: [],
  };
  const userPlace = placeOf(profileData.basics);

  console.log(`Seeding ${STARTUPS.length} verified French and European tech companies...`);

  // Remove defunct bankrupt entity if present
  await prisma.startup.deleteMany({
    where: { source: "EU", externalId: "northvolt" },
  });

  for (const startup of STARTUPS) {
    const fit = matchStartup(startup, profileData, userPlace, now);
    const data = {
      source: startup.source,
      externalId: startup.externalId,
      company: startup.company,
      website: startup.website,
      summary: startup.summary,
      details: startup.details,
      location: startup.location,
      remote: startup.remote,
      stage: startup.stage,
      roles: startup.roles,
      emails: startup.emails,
      links: startup.links,
      postedAt: startup.postedAt ? new Date(startup.postedAt) : null,
      score: fit.score,
      reasons: fit.reasons,
      scoredWith: MATCH_VERSION,
      seenAt: now,
    };

    await prisma.startup.upsert({
      where: {
        source_externalId: {
          source: startup.source,
          externalId: startup.externalId,
        },
      },
      create: data,
      update: data,
    });
    console.log(`  ✓ ${startup.company} (${startup.location}) — Score: ${fit.score}`);
  }

  const total = await prisma.startup.count();
  const franceCount = await prisma.startup.count({
    where: {
      OR: [
        { location: { contains: "France", mode: "insensitive" } },
        { location: { contains: "Paris", mode: "insensitive" } },
      ],
    },
  });
  const remoteCount = await prisma.startup.count({
    where: { remote: true },
  });

  console.log(`Done! Total startups in DB: ${total} (${franceCount} in France, ${remoteCount} remote).`);
  await prisma.$disconnect();
}

seed().catch((error) => {
  console.error("Seeding failed:", error);
  process.exit(1);
});
